"""Export the imagegen HUD to an embedded RGB565 skin (requires Pillow).

Built-in imagegen prompt: front-on dark industrial pixel-art HUD, red health
cross plus eight distinct sci-fi weapon modules, amber lights, blank lower
panels for engine-drawn numbers, no text. Source artwork is retained in resources.
"""
from pathlib import Path
from PIL import Image
root = Path(__file__).resolve().parents[1]
# Remove the generator's surrounding black canvas; retain the complete dashboard.
im = Image.open(root / 'resources/hud-source.png').convert('RGB')
bar = im.crop((0, 180, 2172, 545))
im = Image.new('RGB', (320, 48))
im.paste(bar.crop((0, 0, 278, 365)).resize((32, 48), Image.Resampling.LANCZOS), (0, 0))
edges = [278, 511, 743, 975, 1207, 1440, 1672, 1904, 2172]
for i in range(8):
    cell = bar.crop((edges[i], 0, edges[i+1], 365)).resize((36, 48), Image.Resampling.LANCZOS)
    im.paste(cell, (32 + i * 36, 0))
values = [(r >> 3) << 11 | (g >> 2) << 5 | (b >> 3) for r, g, b in im.getdata()]
lines = [', '.join(f'0x{x:04x}' for x in values[i:i+16]) for i in range(0, len(values), 16)]
(root / 'src/ui/hud_skin.h').write_text('// SPDX-License-Identifier: GPL-2.0-or-later\n'
    '// Generated by scripts/export-hud.py from resources/hud-source.png.\n'
    '#pragma once\n#include <cstdint>\n'
    'inline constexpr int hud_width = 320, hud_height = 48;\n'
    'inline constexpr int hud_health_width = 32, hud_slot_width = 36, hud_weapon_count = 8;\n'
    'inline constexpr uint16_t hud_pixels[] = {\n' + ',\n'.join(lines) + '\n};\n')
