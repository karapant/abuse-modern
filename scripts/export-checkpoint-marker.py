"""Pack the imagegen checkpoint badge into a 16-pixel, indexed game sprite.

Built-in ImageGen prompt:
Generate ONE original pixel-art game UI icon on an actually transparent
background: an industrial checkpoint/save badge. Front-facing, flat
orthographic square metal badge with clipped corners, deep charcoal plate,
bright amber border, one bold pale amber floppy-disk save glyph, and a tiny
downward-pointing tab built into the bottom edge. Use chunky hard-edged pixels,
simple silhouette and strong contrast so the icon reads clearly at 18–22
pixels high. Keep the entire badge centered with tight clear padding. No words,
numbers, shadows outside the badge, backdrop, watermark, gradients,
antialiasing, or extra icons. Original design for a retro industrial sci-fi
game HUD.
"""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
source = Image.open(root / 'resources/checkpoint-marker.png').convert('RGBA')
bounds = source.getchannel('A').point(lambda a: 255 if a >= 192 else 0).getbbox()
badge = source.crop(bounds).resize((16, 16), Image.Resampling.BOX)
rows = []
for y in range(badge.height):
    row = []
    for x in range(badge.width):
        r, g, b, a = badge.getpixel((x, y))
        row.append(0 if a < 128 else 1 if r < 100 else 2 if g < 182 else 3)
    rows.append('    ' + ', '.join(map(str, row)) + ',')
(root / 'src/ui/checkpoint_marker.h').write_text(
    '// SPDX-License-Identifier: GPL-2.0-or-later\n'
    '// Generated by scripts/export-checkpoint-marker.py.\n'
    '#pragma once\n#include <cstdint>\n'
    'inline constexpr int checkpoint_marker_size = 16;\n'
    'inline constexpr uint8_t checkpoint_marker[] = {\n' + '\n'.join(rows) + '\n};\n')
